import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WAREHOUSE_PACK, WAREHOUSE_BOUNDARY, isWarehousePack } from '../app/src/verticals/warehouse/pack.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
assert.equal(WAREHOUSE_PACK.pack_id, 'warehouse');
assert.equal(WAREHOUSE_PACK.name, 'Warehouse');
assert.equal(WAREHOUSE_PACK.version, '0.1.0');
assert.equal(isWarehousePack(), true);
for (const entity of ['StorageBin', 'Receiving', 'StockAdjustment']) assert(WAREHOUSE_PACK.domain_entities.includes(entity));
for (const dependency of ['commerce', 'inventory', 'customers', 'locations', 'fulfillment', 'audit']) assert(WAREHOUSE_PACK.core_dependencies.includes(dependency));
for (const forbidden of WAREHOUSE_BOUNDARY.forbidden_parallel_authorities) assert(!WAREHOUSE_PACK.domain_entities.includes(forbidden));
for (const relative of Object.values(WAREHOUSE_BOUNDARY.existing_modules)) assert(fs.existsSync(path.join(root, relative)), `existing module missing: ${relative}`);
const inventorySource = fs.readFileSync(path.join(root, WAREHOUSE_BOUNDARY.existing_modules.inventory), 'utf8');
const ledgerSource = fs.readFileSync(path.join(root, WAREHOUSE_BOUNDARY.existing_modules.ledger), 'utf8');
const locationsSource = fs.readFileSync(path.join(root, WAREHOUSE_BOUNDARY.existing_modules.locations), 'utf8');
const fulfillmentSource = fs.readFileSync(path.join(root, WAREHOUSE_BOUNDARY.existing_modules.fulfillment), 'utf8');
assert.match(inventorySource, /export function applyStockChange/);
assert.match(ledgerSource, /export function recordInventoryMovement/);
assert.match(locationsSource, /export async function loadOrganizationLocations/);
assert.match(locationsSource, /export function selectOrganizationLocation/);
assert.match(fulfillmentSource, /export function advanceFulfillmentOrder/);
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.product, 'commerce');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.inventory_stock, 'inventory');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.inventory_movement, 'inventory');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.organization_location, 'locations');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.order, 'commerce');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.customer, 'customers');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.fulfillment, 'fulfillment');
assert.equal(WAREHOUSE_BOUNDARY.bridges_to_core.audit, 'audit');
assert.equal(WAREHOUSE_PACK.configuration.implementation, 'existing');
assert.equal(WAREHOUSE_PACK.configuration.niche_switch, 'config.warehouseEnabled=true');
assert.deepEqual(WAREHOUSE_PACK.routes, []);
console.log('Phase 13.9.1 Warehouse Pack Boundary Regression: PASS');
