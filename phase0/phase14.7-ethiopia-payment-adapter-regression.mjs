import assert from 'node:assert/strict';
import { resolveCountryPaymentAdapterMapping, requireCountryPaymentAdapter, countryPaymentAdapterContract } from '../app/src/country-payment-adapter-mapping.js';
const mapping = resolveCountryPaymentAdapterMapping('ET');
assert.equal(mapping.countryCode, 'ET');
assert.equal(mapping.currency, 'ETB');
assert.deepEqual(mapping.providers, ['telebirr', 'cbe']);
assert.deepEqual(mapping.channels, ['api', 'sms', 'manual']);
assert.equal(mapping.providerMetadata.find(x => x.id === 'telebirr').registered, true);
assert.equal(mapping.providerMetadata.find(x => x.id === 'cbe').registered, true);
assert.equal(mapping.providerMetadata.find(x => x.id === 'telebirr').capabilities.initiate, false);
const resolved = requireCountryPaymentAdapter('ET', 'telebirr', 'api');
assert.equal(resolved.provider.id, 'telebirr');
assert.equal(resolved.channel.id, 'api');
assert.equal(resolved.executable, false);
assert.equal(resolved.integrationStatus, 'deferred');
assert.equal(countryPaymentAdapterContract.persistence, 'none');
assert.equal(countryPaymentAdapterContract.ownsPaymentState, false);
assert.equal(countryPaymentAdapterContract.ownsPaymentLedger, false);
assert.equal(countryPaymentAdapterContract.executesProviderCalls, false);
assert.throws(() => requireCountryPaymentAdapter('ET', 'mpesa', 'api'), /not mapped/);
assert.throws(() => requireCountryPaymentAdapter('ET', 'telebirr', 'unknown'), /not mapped/);
console.log('Phase 14.7 Ethiopia Payment Adapter Mapping Regression: PASS');
