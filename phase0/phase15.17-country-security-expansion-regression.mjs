import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AUTHZ, authorize } from '../backend/lib/authorization.js';
import { COUNTRY_SECURITY } from '../backend/lib/country-security-isolation.js';
import { countrySecurityExpansionDecision, countrySecurityExpansionStatus, countrySecurityExpansionContract } from '../backend/lib/country-security-expansion.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'backend/lib/country-security-expansion.js'), 'utf8');
const organization = { id: 'org-a', country: 'ET' };
const tenant = { chatId: 'chat-a', organizationId: 'org-a' };
const location = { id: 'loc-a', organizationId: 'org-a' };
const session = { userId: 'user-a', chatId: 'chat-a', organizationId: 'org-a', role: 'owner' };
let checks = 0;
const eq = (a,b,m) => { checks++; assert.equal(a,b,m); };
const ok = (v,m) => { checks++; assert.equal(Boolean(v),true,m); };

eq(countrySecurityExpansionStatus('ET'),'active_country_pack','ET active');
eq(countrySecurityExpansionStatus('KE'),'active_country_pack','KE active');
eq(countrySecurityExpansionStatus('TZ'),'active_country_pack','TZ active');
eq(countrySecurityExpansionStatus('NG'),'active_country_pack','NG active');
eq(countrySecurityExpansionStatus('GH'),'strategic_candidate','GH candidate');
eq(countrySecurityExpansionStatus('ZM'),'strategic_candidate','ZM candidate');
eq(countrySecurityExpansionStatus('UG'),'regional_country_boundary_only','UG regional-only');
eq(countrySecurityExpansionStatus('CI'),'regional_country_boundary_only','CI regional-only');
eq(countrySecurityExpansionStatus('CM'),'regional_country_boundary_only','CM regional-only');
eq(countrySecurityExpansionStatus('XX'),'unknown','unknown country');
eq(countrySecurityExpansionDecision(session,tenant,organization,location,'ET','orders','orders:view'),AUTHZ.ALLOW,'active matching country delegates to canonical auth');
eq(countrySecurityExpansionDecision(session,tenant,organization,location,'KE','orders','orders:view'),COUNTRY_SECURITY.DENY,'country mismatch denied');
eq(countrySecurityExpansionDecision(session,tenant,organization,location,'GH','orders','orders:view'),COUNTRY_SECURITY.DENY,'candidate denied until activated');
eq(countrySecurityExpansionDecision(session,tenant,organization,location,'UG','orders','orders:view'),COUNTRY_SECURITY.DENY,'regional-only denied until country overlay');
eq(countrySecurityExpansionDecision(session,tenant,organization,location,'XX','orders','orders:view'),COUNTRY_SECURITY.DENY,'unknown denied');
const viewer = {...session, role:'viewer'};
eq(countrySecurityExpansionDecision(viewer,tenant,organization,location,'ET','orders','orders:view'),AUTHZ.DENY,'country layer does not bypass role authorization');
eq(authorize(session,organization,location,'orders','orders:view'),AUTHZ.ALLOW,'canonical authorization unchanged');
const contract = countrySecurityExpansionContract();
eq(contract.persistence,'none','no persistence');
eq(contract.activation,'active_country_pack_only','activation boundary');
eq(contract.candidateActivation,'manual_country_pack_activation_required','candidate gate');
eq(contract.regionalActivation,'country_overlay_required','regional overlay gate');
for (const key of Object.keys(contract)) ok(!/^owns.*Store$/.test(key) || contract[key] === false, `no ownership store: ${key}`);
ok(!source.includes('country-permission-store'),'no duplicate permission store');
ok(!source.includes('country-membership'),'no duplicate membership authority');
console.log('Phase 15.17 Country Security / Isolation Expansion Regression: PASS');
console.log(`Golden assertions: ${checks} PASS / 0 FAIL`);
console.log('Active country pack enforcement: PASS');
console.log('Candidate/regional fail-closed enforcement: PASS');
console.log('Canonical tenant/location/authorization delegation: PASS');
console.log('No duplicate country security authority: PASS');
